"""Rank-4 Hermitian unimodular lattices over O = Z[alpha], alpha = (1+sqrt(-23))/2, from codes.

For a split prime p (here residue map O/pO = F_p x F_p via the two roots of x^2 - x + 6 mod p):
  P_C = { x in O^4 : x mod p in C1 x C2 },  C2 = C1^perp,   h(x,y) = (1/p) sum x_i conj(y_i).
Z-structure: O-element a + b*alpha <-> (a,b). Trace form Tr h(x,y) = 2 Re h.
We compute the 8-dim trace lattice (P, Tr h): det must be 23^4 (Hermitian unimodular), and its minimum
(= 2 * Hermitian minimum)."""
import sys, itertools, json, math
import numpy as np
from fractions import Fraction as Fr
from sympy import Matrix, ZZ
from sympy.matrices.normalforms import hermite_normal_form

D = 23
def roots_mod(p):
    return [r for r in range(p) if (r * r - r + 6) % p == 0]

def residue(a, b, p, rts):
    return tuple((a + b * r) % p for r in rts)

def tr_form_O():
    # Tr(x conj(y)) for basis 1, alpha: Tr(1)=2, Tr(alpha)=1, Tr(alpha*conj alpha)=2*6
    # x conj y with x=a+b al, y=c+d al : a c + a d conj(al) + b c al + b d N(al)
    # Tr = 2ac + ad*1 + bc*1 + 12 bd
    return np.array([[2, 1], [1, 12]])
T2 = tr_form_O()

def fincke_pohst_min(Gm, bound):
    """min and count of nonzero vectors with x^T G x <= bound (G float pos def), small dims."""
    k = Gm.shape[0]
    L = np.linalg.cholesky(Gm)
    U = L.T
    q = np.zeros((k, k))
    for i in range(k):
        q[i, i] = U[i, i] ** 2
        for j in range(i + 1, k):
            q[i, j] = U[i, j] / U[i, i]
    best = [math.inf, 0]
    x = [0] * k
    def rec(i, rem):
        if i < 0:
            if any(x):
                v = bound - rem
                if v < best[0] - 1e-9:
                    best[0], best[1] = v, 1
                elif abs(v - best[0]) < 1e-9:
                    best[1] += 1
            return
        c = -sum(q[i, j] * x[j] for j in range(i + 1, k))
        r = math.sqrt(max(rem, 0) / q[i, i])
        for xi in range(math.ceil(c - r - 1e-9), math.floor(c + r + 1e-9) + 1):
            x[i] = xi
            t = q[i, i] * (xi - c) ** 2
            if t <= rem + 1e-9:
                rec(i - 1, rem - t)
        x[i] = 0
    rec(k - 1, bound)
    return best

def build_P(p, C1_gen):
    rts = roots_mod(p)
    assert len(rts) == 2
    # C1 subspace of F_p^4 from generators, C2 = C1^perp
    M1 = Matrix(C1_gen) if C1_gen else Matrix.zeros(0, 4)
    if M1.rows:
        ns = M1.nullspace()  # over Q; fine for small p? need mod p -> do it manually
    # do linear algebra mod p by brute force (length 4, small p ok for p<=31)
    C1 = set()
    for coeffs in itertools.product(range(p), repeat=len(C1_gen)):
        v = tuple(sum(c * g[i] for c, g in zip(coeffs, C1_gen)) % p for i in range(4))
        C1.add(v)
    if not C1_gen:
        C1 = {(0, 0, 0, 0)}
    C2 = [v for v in itertools.product(range(p), repeat=4)
          if all(sum(a * b for a, b in zip(v, c)) % p == 0 for c in C1)]
    # generators of P_C as Z-lattice in Z^8 (coords (a_i,b_i)): p*O^4 plus lifts of codewords
    gens = []
    for i in range(4):
        for e in ((p, 0), (0, p)):
            v = [0] * 8; v[2 * i], v[2 * i + 1] = e; gens.append(v)
    # lift (r1, r2) in F_p x F_p to a + b alpha with a + b*rts[0] = r1, a + b*rts[1] = r2
    inv = pow((rts[1] - rts[0]) % p, -1, p)
    def lift(r1, r2):
        b = ((r2 - r1) * inv) % p
        a = (r1 - b * rts[0]) % p
        return a, b
    # basis of C1 x C2 generated by (c1,0) and (0,c2)
    for c in C1_gen:
        v = []
        for i in range(4):
            v += list(lift(c[i] % p, 0))
        gens.append(v)
    C2basis = []
    # pick a basis of C2 greedily
    span = {(0, 0, 0, 0)}
    for v in C2:
        if v not in span:
            C2basis.append(v)
            new = set()
            for s in span:
                for t in range(p):
                    new.add(tuple((s[i] + t * v[i]) % p for i in range(4)))
            span = new
        if len(span) == len(C2):
            break
    for c in C2basis:
        v = []
        for i in range(4):
            v += list(lift(0, c[i] % p))
        gens.append(v)
    Hn = hermite_normal_form(Matrix(gens).T).T
    B = np.array(Hn.tolist(), dtype=np.int64)
    B = B[np.abs(B).sum(1) > 0]
    assert B.shape[0] == 8
    # Gram of trace form Tr h, h = (1/p) sum x conj y  ->  Tr h = (1/p) sum_i T2 on coordinate pairs
    T8 = np.kron(np.eye(4, dtype=np.int64), T2)
    G = B @ T8 @ B.T
    assert (G % p == 0).all(), "not integral"
    G //= p
    return B, G, C1, C2basis

def all_subspaces(p, n=4, max_dim=4):
    """All subspaces of F_p^n via reduced row echelon forms (each subspace exactly once)."""
    out = [[]]
    for k in range(1, max_dim + 1):
        for pivots in itertools.combinations(range(n), k):
            # free positions: in row r, columns > pivots[r] that are not pivots
            free = [(r, c) for r in range(k) for c in range(pivots[r] + 1, n) if c not in pivots]
            for vals in itertools.product(range(p), repeat=len(free)):
                rows = [[0] * n for _ in range(k)]
                for r in range(k):
                    rows[r][pivots[r]] = 1
                for (r, c), v in zip(free, vals):
                    rows[r][c] = v
                out.append(rows)
    return out

if __name__ == "__main__":
    p = int(sys.argv[1]); out = sys.argv[2]
    results = []
    subs = all_subspaces(p)
    print(f"p={p}: {len(subs)} subspaces C1", flush=True)
    for gens in subs:
        B, G, C1, C2b = build_P(p, gens)
        det = int(round(np.linalg.det(G.astype(float))))
        mn, cnt = fincke_pohst_min(G.astype(float), 8.5)
        results.append(dict(p=p, C1=[list(g) for g in gens], dim=len(gens), det=det, trace_min=mn, kissing=cnt,
                            B=B.tolist(), G=G.tolist()))
    results.sort(key=lambda r: (-r["trace_min"], r["kissing"]))
    from collections import Counter
    print("det values", Counter(r["det"] for r in results))
    print("trace-min distribution", Counter((r["trace_min"], r["dim"]) for r in results))
    for r in results[:5]:
        print(r["trace_min"], r["kissing"], r["C1"])
    json.dump(results[:50], open(out, "w"))
